"""Rebuild the bundled offline dictionary from a pinned ECDICT CSV (Python 3 stdlib).

Download ecdict.csv at the revision below, then run:
  python3 scripts/build-dictionary.py /path/to/ecdict.csv /path/to/ECDICT/LICENSE
The resulting TypeScript is checked in; normal npm builds never need the network.
"""
import base64
import csv
import gzip
import hashlib
import json
from pathlib import Path
import re
import sys

REVISION = 'bc015ed2e24a7abef49fc6dbbb7fe32c1dadaf8b'
CSV_SHA256 = '1a6947e04785db63613a92e14903cdae7954f7e84860b10e68e5c7cbb3f9c3cf'
SOURCE = 'https://github.com/skywind3000/ECDICT'
root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
if hashlib.sha256(source.read_bytes()).hexdigest() != CSV_SHA256:
    raise ValueError('CSV does not match the pinned ECDICT revision')
license_text = Path(sys.argv[2]).read_text().strip()
entries = {}
variants = []
valid = re.compile(r"^[a-z]+(?:[' -][a-z]+)*$", re.I)


def accepted(word):
    return len(word) <= 100 and len(word.split()) <= 8 and valid.fullmatch(word)


with source.open(encoding='utf-8', newline='') as stream:
    for row in csv.DictReader(stream):
        word = row['word'].strip()
        translation = row['translation'].replace(r'\n', '\n').strip()
        if not accepted(word) or not re.search(r'[\u3400-\u9fff]', translation):
            continue
        entries[word] = [row['phonetic'].strip(), translation]
        for exchange in row['exchange'].split('/'):
            kind, _, forms = exchange.partition(':')
            if kind not in ('p', 'd', 'i', '3', 'r', 't', 's'):
                continue
            for variant in forms.split(','):
                if accepted(variant):
                    variants.append((variant, word))
headwords = len(entries)
for variant, word in variants:
    entries.setdefault(variant, word)
# Keep exact acronym meanings (e.g. US vs us) while allowing ordinary case folding.
for word in sorted(list(entries)):
    value = entries[word]
    entries.setdefault(word.lower(), word if isinstance(value, list) else value)
shards = {}
for word, entry in sorted(entries.items()):
    shards.setdefault(word.lower()[:2], {})[word] = entry
encoded = {prefix: base64.b64encode(gzip.compress(
    json.dumps(shard, ensure_ascii=False, separators=(',', ':')).encode(), mtime=0
)).decode() for prefix, shard in sorted(shards.items())}
sha256 = hashlib.sha256(source.read_bytes()).hexdigest()
header = ('/*! ECDICT — ' + SOURCE + '\nRevision: ' + REVISION + '\n'
          + license_text + '\n*/\n'
          + '// Generated by scripts/build-dictionary.py; do not edit.\n'
          + '// CSV SHA256: ' + sha256 + '\n'
          + f'// {headwords} Chinese headwords, {len(entries)} indexed forms, {len(shards)} prefix shards.\n')
output = root / 'src/adapters/dictionary/data.ts'
output.write_text(header + 'export const dictionaryShards: Record<string, string> = '
                  + json.dumps(encoded, indent=2) + ';\n')
print(json.dumps({'headwords': headwords, 'indexedForms': len(entries), 'shards': len(shards),
                  'bytes': output.stat().st_size, 'csvSha256': sha256}, indent=2))
